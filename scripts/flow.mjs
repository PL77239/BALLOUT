import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/local/bin/google-chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message + '\n' + e.stack));
await page.goto('http://127.0.0.1:47731/');
await page.waitForTimeout(2500);
const press = async (k) => { await page.keyboard.press(k, { delay: 300 }); await page.waitForTimeout(400); };
await press('Enter');
await press('ArrowRight'); await press('ArrowDown'); await press('ArrowDown');
await page.screenshot({ path: 'shots/flow_menu.png' });
for (let i = 0; i < 3; i++) await press('ArrowDown');
await press('Enter');
await page.waitForFunction(() => window.__g && window.__g.phase === 'live', null, { timeout: 60000 });
console.log('game live:', await page.evaluate(() => window.__g.cfg.court + ' ' + window.__g.cfg.mode + ' vs ' + window.__g.hoopers[1].loadout.name));
await press('Escape');
await page.screenshot({ path: 'shots/flow_pause.png' });
await press('Escape');
await page.waitForTimeout(500);
console.log('paused after resume:', await page.evaluate(() => window.__g.paused));
await press('Escape'); await press('Backspace'); await page.waitForTimeout(800);
console.log('back at menu:', await page.evaluate(() => window.__phaser.scene.isActive('menu')));
console.log(errors.join('\n') || 'no errors');
await browser.close();
